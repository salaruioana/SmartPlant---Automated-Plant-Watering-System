//FRAME BUFFER 
// 128 pixeli x 64 pixeli / 8 biti = 1024 bytes
static uint8_t framebuffer[OLED_WIDTH * OLED_HEIGHT / 8];
// defineste o interfata de comunicare cu driverul i2c de la sdk
static i2c_inst_t *oled_i2c;

// FUNCTII INTERNE 
static void oled_send_cmd(uint8_t cmd) {
    uint8_t buf[2] = {0x00, cmd}; // 0x00 = command mode
    i2c_write_blocking(oled_i2c, OLED_ADDR, buf, 2, false);
}

static void oled_send_data(uint8_t *data, size_t len) {
    uint8_t buf[len + 1];
    buf[0] = 0x40; // 0x40 = data mode
    memcpy(buf + 1, data, len);
    i2c_write_blocking(oled_i2c, OLED_ADDR, buf, len + 1, false);
}

// INITIALIZARE SSD1306 
void oled_init(i2c_inst_t *i2c) {
    oled_i2c = i2c;
    sleep_ms(100); // asteapta display sa porneasca

    // Secventa de initializare standard SSD1306
    oled_send_cmd(0xAE); // display off
    oled_send_cmd(0xD5); // set display clock
    oled_send_cmd(0x80);
    oled_send_cmd(0xA8); // set multiplex ratio
    oled_send_cmd(0x3F); // 64 linii
    oled_send_cmd(0xD3); // set display offset
    oled_send_cmd(0x00);
    oled_send_cmd(0x40); // set start line
    oled_send_cmd(0x8D); // charge pump
    oled_send_cmd(0x14); // enable charge pump
    oled_send_cmd(0x20); // memory addressing mode
    oled_send_cmd(0x00); // horizontal addressing
    oled_send_cmd(0xA1); // segment remap
    oled_send_cmd(0xC8); // COM scan direction
    oled_send_cmd(0xDA); // COM pins config
    oled_send_cmd(0x12);
    oled_send_cmd(0x81); // set contrast
    oled_send_cmd(0xCF);
    oled_send_cmd(0xD9); // pre-charge period
    oled_send_cmd(0xF1);
    oled_send_cmd(0xDB); // VCOMH deselect level
    oled_send_cmd(0x40);
    oled_send_cmd(0xA4); // display from RAM
    oled_send_cmd(0xA6); // normal display (nu inversat)
    oled_send_cmd(0xAF); // display on

    oled_clear();
    oled_show();
}

// OPERATII DE BAZA 
void oled_clear(void) {
    memset(framebuffer, 0, sizeof(framebuffer));
}

void oled_show(void) {
    // Seteaza zona de scriere: tot ecranul
    oled_send_cmd(0x21); // column address
    oled_send_cmd(0);    // start
    oled_send_cmd(127);  // end
    oled_send_cmd(0x22); // page address
    oled_send_cmd(0);    // start
    oled_send_cmd(7);    // end (8 pagini x 8 pixeli = 64)

    // Trimite tot framebuffer-ul
    oled_send_data(framebuffer, sizeof(framebuffer));
}

// DESENARE PIXEL 
void oled_draw_pixel(int x, int y, bool on) {
    if (x < 0 || x >= OLED_WIDTH || y < 0 || y >= OLED_HEIGHT) return;
    
    // Fiecare byte controleaza 8 pixeli verticali
    // page = y / 8, bit = y % 8
    int index = x + (y / 8) * OLED_WIDTH;
    if (on)
        framebuffer[index] |= (1 << (y % 8));
    else
        framebuffer[index] &= ~(1 << (y % 8));
}

// DESENARE TEXT (font 5x7) 
void oled_draw_text(int x, int y, const char *text) {
    while (*text) {
        char c = *text++;
        if (c < 32 || c > 126) c = 32; // caractere necunoscute = spatiu
        
        const uint8_t *glyph = font5x7[c - 32];
        for (int col = 0; col < 5; col++) {
            uint8_t column = glyph[col];
            for (int row = 0; row < 7; row++) {
                oled_draw_pixel(x + col, y + row, (column >> row) & 1);
            }
        }
        x += 6; // 5 pixeli litera + 1 spatiu
        if (x > OLED_WIDTH - 5) break; // nu iesi din ecran
    }
}

// TEXT MARE (2x) 
void oled_draw_text_large(int x, int y, const char *text) {
    while (*text) {
        char c = *text++;
        if (c < 32 || c > 126) c = 32;
        
        const uint8_t *glyph = font5x7[c - 32];
        for (int col = 0; col < 5; col++) {
            uint8_t column = glyph[col];
            for (int row = 0; row < 7; row++) {
                bool on = (column >> row) & 1;
                // Fiecare pixel devine 2x2
                oled_draw_pixel(x + col*2,     y + row*2,     on);
                oled_draw_pixel(x + col*2 + 1, y + row*2,     on);
                oled_draw_pixel(x + col*2,     y + row*2 + 1, on);
                oled_draw_pixel(x + col*2 + 1, y + row*2 + 1, on);
            }
        }
        x += 11; // 10 pixeli litera + 1 spatiu
        if (x > OLED_WIDTH - 10) break;
    }
}

// DREPTUNGHI 
void oled_draw_rect(int x, int y, int w, int h, bool on) {
    for (int i = x; i < x + w; i++) {
        oled_draw_pixel(i, y, on);
        oled_draw_pixel(i, y + h - 1, on);
    }
    for (int i = y; i < y + h; i++) {
        oled_draw_pixel(x, i, on);
        oled_draw_pixel(x + w - 1, i, on);
    }
}

void oled_draw_filled_rect(int x, int y, int w, int h, bool on) {
    for (int i = x; i < x + w; i++)
        for (int j = y; j < y + h; j++)
            oled_draw_pixel(i, j, on);
}

// BARA DE PROGRES 
void oled_draw_progress_bar(int x, int y, int w, int h, int percent) {
    if (percent < 0) percent = 0;
    if (percent > 100) percent = 100;
    
    oled_draw_rect(x, y, w, h, true); // contur
    int fill = (w - 2) * percent / 100;
    oled_draw_filled_rect(x + 1, y + 1, fill, h - 2, true); // umplere
}
